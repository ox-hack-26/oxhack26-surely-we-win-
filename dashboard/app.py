"""ClinicDrift HRT demo: run from dashboard/ with streamlit run app.py."""
import json
import pandas as pd
import plotly.express as px
import os
from pathlib import Path
import streamlit as st
from dotenv import load_dotenv
from ui.handoff import load_handoff, replay_view, alarm_for_week
from ui.costs import recompute
from ui.real_charts import catch_chart, drift_chart

load_dotenv(Path(__file__).parent / '.env')
st.set_page_config(page_title='ClinicDrift | OxHack',page_icon='👁️',layout='wide')
st.markdown("""<style>.block-container{padding-top:1.4rem;max-width:1450px}div[data-testid='stMetric']{background:rgba(128,128,128,.12);border:1px solid rgba(128,128,128,.25);padding:14px;border-radius:12px}div[data-testid='stMetric'] [data-testid='stMetricValue'],div[data-testid='stMetric'] [data-testid='stMetricLabel']{color:var(--text-color)!important}</style>""",unsafe_allow_html=True)
page = st.sidebar.radio(
    "Navigation",
    ["Monitoring", "Results"],
    horizontal=True,
)

st.title('ClinicDrift  /  Reliability Command Centre')
st.caption('OxHack 2026 · HRT: Best Use of Data for Predictions & Decision Making · Tiger Data integration optional')
st.warning('RESEARCH DEMONSTRATOR — Simulated clinics and timelines. Expert hindsight is not available to a real-time decision maker. No automatic clinical withdrawal.')

try:
    weekly, clinics, settings = load_handoff()
except (FileNotFoundError, ValueError, KeyError, json.JSONDecodeError) as exc:
    st.error(f'Handoff data unavailable or invalid: {exc}'); st.stop()

if page == "Results":
    st.header("ClinicDrift Backtest Results")
    st.caption(
        "Historical simulation and policy comparison. "
        "Results are not clinical deployment outcomes."
    )

    root = Path(__file__).resolve().parents[1]
    summary_path = root / "sample-data" / "backtest_summary.json"
    sweep_path = root / "sample-data" / "backtest_sweep.csv"

    with summary_path.open() as f:
        summary = pd.DataFrame(json.load(f))

    sweep = pd.read_csv(sweep_path)

    st.subheader("Policy comparison")

    st.dataframe(
        summary,
        hide_index=True,
        width="stretch",
    )

    fig = px.bar(
        summary,
        x="policy",
        y="total_cost_gbp",
        color="policy",
        title="Total simulated cost by policy",
        labels={
            "policy": "Decision policy",
            "total_cost_gbp": "Total cost (£)",
        },
    )

    fig.update_layout(showlegend=False)

    st.plotly_chart(fig, width="stretch")

    st.subheader("Cost sensitivity")

    fig2 = px.line(
        sweep,
        x="review_cost",
        y="total_cost_gbp",
        color="policy",
        markers=True,
        labels={
            "review_cost": "Review cost (£)",
            "total_cost_gbp": "Total simulated cost (£)",
            "policy": "Decision policy",
        },
    )

    st.plotly_chart(fig2, width="stretch")

    st.subheader("Detailed cost sweep")

    st.dataframe(
        sweep,
        hide_index=True,
        width="stretch",
    )

    st.caption(
        "Source: sample-data/backtest_summary.json "
        "and sample-data/backtest_sweep.csv. "
        "These files are regenerated by the engine."
    )

    st.stop()

clinic_map = {c['clinic_id']:c for c in clinics}
choices = sorted(weekly.clinic_id.unique(),key=lambda c:(c!='US-WEAR-01',c))
with st.sidebar:
    st.header('Replay control')
    clinic = st.selectbox('Simulated clinic',choices,format_func=lambda c:f"{c} — {clinic_map.get(c,{}).get('site','')}")
    series = weekly[weekly.clinic_id==clinic].sort_values('week')
    week = st.slider('Week',int(series.week.min()),int(series.week.max()),9 if clinic=='US-WEAR-01' else int(series.week.max()))
    st.divider()
    st.header('Decision costs (illustrative £)')
    defaults = settings['costs']
    missed = st.slider('Cost per missed referable case (£)',0,30000,int(defaults['missed_case']),500)
    false = st.slider('Cost per unnecessary referral (£)',0,1000,int(defaults['false_referral']),25)
    review = st.slider('Cost of clinical review (£)',0,100000,int(defaults['review']),1000)
    horizon = st.slider('Decision horizon (weeks)',1,12,int(defaults['horizon_weeks']))
    st.divider()
    show_hindsight=st.checkbox('Show hindsight (evaluation only)',value=False)
    st.caption('Hindsight is hidden by default to avoid future-label leakage.')

visible = replay_view(weekly,clinic,week)
current=visible.iloc[-1]
meta=clinic_map.get(clinic,{})
decision=recompute(current,settings['reference'],missed,false,review,horizon)
first_alarm=series.loc[series.alarm,'week'].min() if series.alarm.any() else None
st.caption(f"{meta.get('site',clinic)} · {meta.get('country','')} · {meta.get('note','')}")
cols=st.columns(5)
cols[0].metric('ClinicDrift catch rate',f"{current.catch_rate:.1%}")
cols[1].metric('90% belief band',f"{current.catch_low:.1%} – {current.catch_high:.1%}")
cols[2].metric('Naive estimate',f"{current.est_sensitivity:.1%}")
cols[3].metric('Drift AUC',f"{current.drift_auc:.3f}")
cols[4].metric('Review status','ALARM' if bool(current.alarm) else 'MONITOR')
left,right=st.columns([2.1,1],gap='large')
with left:
    st.subheader('Catch-rate monitoring')
    st.plotly_chart(catch_chart(series[series.week<=week],show_hindsight),width='stretch')
    if show_hindsight:
        st.warning('Evaluation-only hindsight: full expert grades are deliberately withheld in the normal replay.')
    st.caption('Solid = combined belief; dashed = naive image-only estimate; shaded = 90% belief band. Later expert labels enter the belief only when available.')
    st.subheader('Distribution shift')
    st.plotly_chart(drift_chart(visible),width='stretch')
with right:
    st.subheader('Decision / evidence')
    st.write(f"**Replay:** Week {week} · {str(current.week_start.date())}")
    reason = current.alarm_reason
    if reason == 'drift':
        st.warning("Outside validated conditions: catch rate can't be verified.")
    elif reason == 'harm':
        st.error(f"Estimated catch rate dropped to {current.catch_rate:.1%}.")
    else:
        st.info("Monitoring: no new alarm reason.")
    st.write(f"**First latched alarm:** {'Week '+str(int(first_alarm)) if first_alarm is not None and first_alarm<=week else 'Not yet'}")
    st.metric('Recomputed expected extra harm',f"£{decision['expected_harm']:,.0f}")
    st.metric('Review cost',f"£{review:,.0f}")
    st.info('**Cost slider recommends review**' if decision['review_recommended_this_week'] else '**Cost slider recommends monitoring**')
    st.caption('Slider decision is recalculated for the selected week. Original engine alarm remains latched; slider changes do not rewrite the historical backtest.')
    st.caption(decision['assumption'])
    st.write(f"**Expert-graded positive cases already arrived:** {int(current.graded_cases)}")
    st.write(f"**Already-graded cases caught:** {int(current.graded_caught)}")
    alarm = alarm_for_week(clinic, week)
    if alarm:
        st.success("Engine alarm evidence available")
        st.json(alarm)

st.divider()
st.subheader('Replay history')
st.dataframe(visible[['week','n_scans','catch_rate','catch_low','catch_high','est_sensitivity','drift_auc','graded_cases','graded_caught','alarm','alarm_reason']],hide_index=True,width='stretch')
st.caption('Source: sample-data/ handoff; all clinic weeks are simulated. No database write occurs from this dashboard.')
